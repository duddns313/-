/* 효과 묶음을 합친다 (flag는 이어 붙인다) */
function y1Fx(...parts) {
  const out = {};
  for (const p of parts) for (const k in p) {
    if (k === 'flag') out.flag = [].concat(out.flag || [], p.flag);
    else if (k === 'rel') out.rel = Object.assign({}, out.rel, p.rel);
    else out[k] = p[k];
  }
  return out;
}
